/* Portable regression fixtures for the human-readable BOOTCHAIN.TXT contract. */

#include "boot_report.h"

#include <stdio.h>
#include <string.h>

static void init_info(boot_chain_info_t *info)
{
    memset(info, 0, sizeof(*info));
    info->skip_hdd[0] = -1;
    info->skip_hdd[1] = -1;
    info->skip_hdd[2] = -1;
    info->payload_read_result = -1;
    info->payload_kelf_result = -1;
    info->sysconf_mount_result = -6;
    info->system_mount_result = -7;
}

static int contains(const char *text, const char *needle)
{
    return strstr(text, needle) != NULL;
}

